"""Check 2 (the free AI mercenary hire, report §3.2 at research commit 7d7b613): scan every consecutive
watched-turn pair for a live mercenary pool offer that disappears, and where its (label, type, troops,
quality) reappear. A hire corroborated looks like:

  - the pool slot (x, y) held a live offer at turn t, empty (or overwritten) at t+1;
  - an army of an AT-WAR AI nation gained a unit slot at t+1 with the offer's exact label/type/troops/quality
    (merc label byte non-zero, name copied);
  - that army was within Chebyshev 4 of (x, y) at turn t, with money > 50;
  - no payment: the army's money and the nation's treasury moved only by the other documented mechanisms
    (purse normalisation 500-1000 at own cities, recruitment spending), never by a hire price.

The +0x274 byte gate is in-memory only: it is listed as unobservable. Pool slots that merely change
(the market refresh overwrites offers) are reported separately from hires.

    python3 runs/experiments/ai_turn/analyze_merc.py      # writes merc_analysis.txt to the tracked data dir
"""
import glob, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from paths import DATA
from common import write_new, latest

HUMAN = 'Rome'


def load_turns():
    out = {}
    turns = set(int(m.group(1)) for m in
                (re.search(r'AUTO(\d+)\.SAV', p) for p in glob.glob(DATA + 'turns/AUTO*'))
                if m)
    for t in sorted(turns):
        p = latest('%sturns/AUTO%04d.SAV.json' % (DATA, t))
        with open(p) as f:
            d = json.load(f)
        out[d['turn']] = d
    return out


def cheb4(ax, ay, bx, by):
    return max(abs(ax - bx), abs(ay - by)) <= 4


def main():
    turns = load_turns()
    lines = ['# Mercenary pool scan (check 2), generated by analyze_merc.py',
             '# rules: research report 2026-10-07-strategic-ai-turn.md §3.2 (commit 7d7b613)']
    hires, gone_elsewhere = 0, 0
    for t in sorted(turns):
        before, after = turns[t], turns.get(t + 1)
        if after is None:
            continue
        pool_b = {m['slot']: m for m in before['mercenaries']}
        pool_a = {m['slot']: m for m in after['mercenaries']}
        arm_b = {a['id']: a for a in before['armies']}
        nb = {n['name']: n for n in before['nations']}
        changed = False
        for slot, m in sorted(pool_b.items()):
            a = pool_a.get(slot)
            if a is not None and a == m:
                continue                       # untouched offer
            changed = True
            what = 'refreshed' if a is not None else 'emptied'
            # where did the offer's exact stats reappear among armies at t+1?
            match = []
            for army in after['armies']:
                for u in army['units']:
                    if (u.get('merc') == m['label'] and u['troops'] == m['troops']
                            and u['quality'] == m['quality'] and u['type'] == m['type']):
                        match.append(army)
            if not match:
                gone_elsewhere += 1
                lines.append('turn %04d->%04d slot %d %s: %s, no army holds its exact stats at t+1'
                             % (t, t + 1, slot, what, m))
                continue
            for army in match:
                b = arm_b.get(army['id'])
                nation = nb.get(army['owner'], {})
                dist = cheb4(b['x'], b['y'], m['x'], m['y']) if b else None
                lines.append('turn %04d->%04d slot %d %s: %s -> army %d (%s) at t+1' % (t, t + 1, slot, what, m, army['id'], army['owner']))
                lines.append('  army at t: pos (%s,%s) money %s wars %s | t+1: pos (%s,%s) money %s'
                             % (b['x'] if b else '?', b['y'] if b else '?', b['money'] if b else '?',
                                nation.get('wars'), army['x'], army['y'], army['money']))
                lines.append('  distance <= 4: %s | at war: %s | money > 50: %s | gained unit: %s'
                             % (dist, bool(nation.get('wars')),
                                (b['money'] > 50) if b else '?',
                                not any(u.get('merc') == m['label'] and u['troops'] == m['troops']
                                       for u in (b['units'] if b else []))))
                hires += 1
        if not changed and pool_b:
            pass
    lines.append('')
    lines.append('# pool slots whose stats reappeared in an army (candidate hires, judged above): %d' % hires)
    lines.append('# pool slots emptied/refreshed without a stat match (market refresh / human hires / expiry): %d' % gone_elsewhere)
    txt = '\n'.join(lines) + '\n'
    p = write_new(DATA + 'merc_analysis.txt', txt)
    print(txt)
    print('(written to %s)' % p)


if __name__ == '__main__':
    main()
