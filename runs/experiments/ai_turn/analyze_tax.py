"""Check 1 (week-11 tax policy, report §2.3 as corrected at research commit 7d7b613): for every watched
week-11 turn, compare each AI nation's +0x44A tax in the turn's save against the next save, and evaluate
the decompile's three sequential rules against the trigger values read from the SAME before-save:

    if (unity < 650  or treasury > wealth/2000):  tax = max(5, tax - 6)
    if (treasury < 0  or (own <= threat and treasury < 1000)):  tax = min(40, tax + 9)
    if (treasury > 0 and unity < 500):            tax = 0

`own <= threat` (the §2.1 threat budget) is computed in memory, not in the save: when the raise fires with
treasury >= 0 and < 1000, the table records it as INDIRECT (the raise itself is the evidence the branch held).
The before-save is the human turn's autosave (turn start): the AI's own economy phase may spend treasury
before the tax block reads it, so a trigger read at turn start is the closest observable value — mismatches
are reported, not hidden. Rome is the human seat and never touches the Taxation slider: it is the control.

    python3 runs/experiments/ai_turn/analyze_tax.py          # writes tax_analysis.txt to the tracked data dir
"""
import glob, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from paths import DATA
from common import write_new, latest

HUMAN = 'Rome'


def load_turns():
    out = {}
    turns = set(int(m.group(1)) for m in
                (re.search(r'AUTO(\d+)\.SAV', p) for p in glob.glob(DATA + 'turns/AUTO*'))
                if m)
    for t in sorted(turns):
        p = latest('%sturns/AUTO%04d.SAV.json' % (DATA, t))
        m = re.search(r'AUTO(\d+)\.json', p)
        with open(p) as f:
            d = json.load(f)
        out[d['turn']] = d
    return out


def predicted(tax, unity, treasury, wealth):
    """The three sequential rules; returns (final_tax, [applied rule labels])."""
    rules = []
    if unity < 650 or treasury > wealth // 2000:
        tax = max(5, tax - 6)
        rules.append('cut')
    if treasury < 0:
        tax = min(40, tax + 9)
        rules.append('raise(deficit)')
    elif treasury < 1000:
        rules.append('raise(threat)?')      # branch needs own<=threat, unreadable from the save
        return None, rules                   # prediction ambiguous: cannot decide without the threat budget
    if treasury > 0 and unity < 500:
        tax = 0
        rules.append('zero')
    return tax, rules


def main():
    turns = load_turns()
    lines = ['# Week-11 tax analysis (check 1), generated by analyze_tax.py',
             '# rules: research report 2026-10-07-strategic-ai-turn.md §2.3 (commit 7d7b613)',
             '# EMPIRICAL PLACEMENT (this run): the tax write lands in the transition FROM the week-9 turn -',
             '# the week-11 save already shows it, the week-11->new-season transition shows none. So',
             '# before = the week-9 turn autosave, after = the week-11 autosave. This corrects the report\'s',
             '# "immediately before the quarterly tick": the block fires one weekly tick earlier, at 9->11.',
             '# trigger values are the BEFORE save\'s; the AI\'s in-turn spending before the tax block is not observable']
    n_ok = n_bad = n_amb = 0
    for t in sorted(turns):
        before = turns[t]
        if before['week'] != 9:
            continue
        after = turns.get(t + 1)
        if after is None:
            lines.append('# turn %04d: week 11 but no next save watched' % t)
            continue
        lines.append('')
        lines.append('## %s -> %s (%s)' % (before['save'], after['save'], after['date']))
        lines.append('| nation | tax b->a | unity | treasury | wealth | trs>W/2000 | predicted | rules | verdict |')
        lines.append('|---|---|---|---|---|---|---|---|---|')
        ab = {n['name']: n for n in after['nations']}
        for n in before['nations']:
            a = ab.get(n['name'])
            if a is None:
                lines.append('| %s | gone (eliminated?) |  |  |  |  |  |  | n/a |' % n['name'])
                continue
            if not n['alive']:
                continue
            pred, rules = predicted(n['tax'], n['unity'], n['treasury'], n['wealth'])
            rich = n['treasury'] > n['wealth'] // 2000
            moved = '%d->%d' % (n['tax'], a['tax'])
            if n['name'] == HUMAN:
                verdict = 'control (human seat, slider untouched): %s' % ('unchanged' if n['tax'] == a['tax'] else 'MOVED')
            elif pred is None:
                verdict = 'ambiguous (threat budget unreadable)'
                n_amb += 1
            elif pred == a['tax']:
                verdict = 'match'
                n_ok += 1
            else:
                verdict = 'MISMATCH'
                n_bad += 1
            lines.append('| %s | %s | %d | %d | %d | %s | %s | %s | %s |' % (
                n['name'], moved, n['unity'], n['treasury'], n['wealth'], rich,
                'n/a' if pred is None else pred, '+'.join(rules) or 'none', verdict))
    lines.append('')
    lines.append('# totals: %d match, %d mismatch, %d ambiguous' % (n_ok, n_bad, n_amb))
    txt = '\n'.join(lines) + '\n'
    p = write_new(DATA + 'tax_analysis.txt', txt)
    print(txt)
    print('(written to %s)' % p)


if __name__ == '__main__':
    main()
