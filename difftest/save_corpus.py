"""The save corpus (owner 2026-11-04: "create a corpus of saves ... so that you can continue later"; kept in the GitHub
release `ic2-save-corpus`, the owner's choice): every game we play, packed so any later session can continue it
(`difftest.campaign --resume`) or start a new run from any of its years.

    python3 -m difftest.save_corpus publish GAME_DIR [GAME_DIR ...]   # pack, upload, append to the index
    python3 -m difftest.save_corpus fetch GAME [--into artifacts/save-corpus]   # download + unpack the latest pack of GAME
    python3 -m difftest.save_corpus list [--min-year-bc 267]          # what the index holds

A pack is `<game>-t<last turn>.tar.gz`: the game folder (original/ checkpoints and receipt with RandSeed, remake/ natives,
turns.jsonl, run.json, summary.json, resumes.jsonl) without its anchored*/ replays (those are regenerated by
difftest.anchored). Names carry the last turn, so a longer pack of the same game is a new asset, never a replaced one
(rule 6). The index `runs/experiments/data/save-corpus/index.jsonl` is append-only: one line per published pack with every
turn's start (difftest.late_starts.catalogue: date, year, human nation, checkpoint path inside the pack, sha256,
randseed_after).
"""
import argparse
import json
import subprocess
import sys
import tarfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from difftest.late_starts import catalogue  # noqa: E402

RELEASE = "ic2-save-corpus"
INDEX = ROOT / "runs/experiments/data/save-corpus/index.jsonl"
STAGE = ROOT / "artifacts/save-corpus"


def gh(*args, check=True):
    p = subprocess.run(["gh", *args], capture_output=True, text=True, cwd=ROOT)
    if check and p.returncode:
        raise SystemExit(f"gh {' '.join(args)} failed: {p.stderr.strip()[-800:]}")
    return p


def publish(game_dir):
    g = Path(game_dir).resolve()
    rows = [json.loads(l) for l in (g / "turns.jsonl").read_text().splitlines() if l.strip()] \
        if (g / "turns.jsonl").exists() else []
    last = rows[-1]["turn"] if rows else 0
    name = f"{g.name}-t{last:03d}.tar.gz"
    STAGE.mkdir(parents=True, exist_ok=True)
    pack = STAGE / name
    if pack.exists():
        raise SystemExit(f"{pack} exists: already published at turn {last} (rule 6: never replaced)")
    with tarfile.open(pack, "w:gz") as t:
        t.add(g, arcname=g.name, filter=lambda ti: None if "/anchored" in ti.name or ti.name.endswith(".log") else ti)
    if gh("release", "view", RELEASE, check=False).returncode:
        gh("release", "create", RELEASE, "--title", RELEASE, "--notes",
           "Save corpus: every played game, to continue it (difftest.campaign --resume) or start from any year. "
           "Index: runs/experiments/data/save-corpus/index.jsonl. Fetch: python3 -m difftest.save_corpus fetch <game>.")
    gh("release", "upload", RELEASE, str(pack))
    starts = catalogue(g)
    for s in starts:
        s["checkpoint"] = str(Path(g.name) / Path(s["checkpoint"]).relative_to(g.relative_to(ROOT)))
    INDEX.parent.mkdir(parents=True, exist_ok=True)
    with open(INDEX, "a") as f:
        f.write(json.dumps({"asset": name, "release": RELEASE, "game": g.name, "source": str(g.relative_to(ROOT)),
                            "last_turn": last, "published": time.strftime("%Y-%m-%dT%H:%M:%S"),
                            "years_bc": sorted({s["year_bc"] for s in starts}, reverse=True), "starts": starts}) + "\n")
    print(f"published {name}: {len(starts)} starts, years BC {sorted({s['year_bc'] for s in starts}, reverse=True)}")


def entries():
    return [json.loads(l) for l in INDEX.read_text().splitlines() if l.strip()] if INDEX.exists() else []


def fetch(game, into):
    packs = [e for e in entries() if e["game"] == game]
    if not packs:
        raise SystemExit(f"{game} is not in {INDEX}")
    e = max(packs, key=lambda x: x["last_turn"])
    into = Path(into)
    into.mkdir(parents=True, exist_ok=True)
    gh("release", "download", RELEASE, "--pattern", e["asset"], "--dir", str(into), "--clobber")
    with tarfile.open(into / e["asset"]) as t:
        t.extractall(into, filter="data")
    print(f"{into / game}: turn {e['last_turn']}; continue with: python3 -m difftest.campaign <start> {into / game} "
          f"--turns N --resume [--original-only]")


def main(argv=None):
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("publish"); p.add_argument("dirs", nargs="+")
    f = sub.add_parser("fetch"); f.add_argument("game"); f.add_argument("--into", default=str(STAGE))
    ls = sub.add_parser("list"); ls.add_argument("--min-year-bc", type=int)
    a = ap.parse_args(argv)
    if a.cmd == "publish":
        for d in a.dirs:
            publish(d)
    elif a.cmd == "fetch":
        fetch(a.game, a.into)
    else:
        latest = {}
        for e in entries():
            if e["game"] not in latest or e["last_turn"] > latest[e["game"]]["last_turn"]:
                latest[e["game"]] = e
        for g, e in sorted(latest.items()):
            ys = [y for y in e["years_bc"] if a.min_year_bc is None or y <= a.min_year_bc]
            if ys:
                print(f"{g}: {e['asset']} (turn {e['last_turn']}), years BC {ys}")


if __name__ == "__main__":
    main()
