"""The differential test history: every comparison ever reported, one JSON line each, and a readable page.

    python3 -m difftest.history record REPORT.json --data run-exp-<name> --verdict "<one line>" [--issue N]
    python3 -m difftest.history render            # rewrites difftest/HISTORY.md from difftest/history.jsonl

`history.jsonl` is append-only (rule 6: a result is never edited or deleted; a correction is a new line that
names the one it corrects with "corrects"). HISTORY.md is generated from it and may be regenerated at any time.
"""
import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG = ROOT / "difftest" / "history.jsonl"
PAGE = ROOT / "difftest" / "HISTORY.md"


def entries():
    return [json.loads(l) for l in LOG.read_text().splitlines() if l.strip()] if LOG.exists() else []


def record(report_path, data, verdict, issue=None, corrects=None, kind=None):
    r = json.loads(Path(report_path).read_text())
    runs = []
    for side in ("a", "b"):
        meta = json.loads((ROOT / r[side]["run"] / "run.json").read_text())
        runs.append({"side": meta["side"], "run": Path(r[side]["run"]).name, "seed": meta.get("seed"),
                     "pins": meta.get("pins"), "start": Path(meta["start"]).name, "start_sha256": meta["start_sha256"],
                     "finished": meta["finished"], "errors": meta["errors"]})
    first = r["first_divergence"]
    row = next((x for x in r["rows"] if x["checkpoint"] == first), None)
    e = {"id": len(entries()) + 1, "recorded": time.strftime("%Y-%m-%dT%H:%M:%S"), "issue": issue,
         "kind": kind or ("self-check" if runs[0]["side"] == runs[1]["side"] else "original-vs-remake"),
         "script": Path(r["script"]).name, "a": runs[0], "b": runs[1], "checkpoints": r["checkpoints"],
         "first_divergence": first, "first_action": row and row.get("action"),
         "first_fields": row and len(row["fields"]), "first_map_cells": row and row["map"]["count"],
         "refusal_differences": [x["checkpoint"] for x in r["rows"] if x.get("refusal_difference")],
         "report": Path(report_path).name, "data": f"runs/experiments/data/{data}/", "verdict": verdict}
    if corrects:
        e["corrects"] = corrects
    with open(LOG, "a") as f:
        f.write(json.dumps(e) + "\n")
    return e


def render():
    es = entries()
    corrected = {e["corrects"]: e["id"] for e in es if e.get("corrects")}
    out = ["# Differential test history: original vs remake",
           "",
           "Generated by `python3 -m difftest.history render` from [`history.jsonl`](history.jsonl) (append-only;",
           "a correction is a new entry). Harness: [README](README.md). Tracker: #228.",
           "",
           "| # | date | issue | kind | script | A | B | first divergence | verdict | data |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for e in es:
        def side(s):
            v = s["side"]
            if s["side"] == "remake":
                v += f" `{(s['pins'] or {}).get('remake_commit', '')[:8]}`"
            elif s.get("seed") is not None:
                v += f" seed {s['seed']}"
            return v
        first = "none" if not e["first_divergence"] else (
            f"`{e['first_divergence']}` after `{(e['first_action'] or {}).get('op', '?')}` "
            f"({e['first_fields']} fields, {e['first_map_cells']} cells)")
        if e["refusal_differences"]:
            first += f"; refusal differences at {', '.join(e['refusal_differences'])}"
        verdict = e["verdict"]
        if e["id"] in corrected:
            verdict = f"~~{verdict}~~ (corrected by #{corrected[e['id']]})"
        if e.get("corrects"):
            verdict = f"corrects #{e['corrects']}: {verdict}"
        issue = f"#{e['issue']}" if e.get("issue") else ""
        out.append(f"| {e['id']} | {e['recorded'][:10]} | {issue} | {e['kind']} | `{e['script']}` | {side(e['a'])} | {side(e['b'])} "
                   f"| {first} | {verdict} | [{e['report']}](../{e['data']}{e['report']}) |")
    PAGE.write_text("\n".join(out) + "\n")
    return PAGE


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    rec = sub.add_parser("record")
    rec.add_argument("report")
    rec.add_argument("--data", required=True)
    rec.add_argument("--verdict", required=True)
    rec.add_argument("--issue", type=int)
    rec.add_argument("--corrects", type=int)
    rec.add_argument("--kind")
    sub.add_parser("render")
    a = ap.parse_args()
    if a.cmd == "record":
        e = record(a.report, a.data, a.verdict, a.issue, a.corrects, a.kind)
        render()
        print(f"history #{e['id']}: {e['kind']} {e['script']} first divergence {e['first_divergence']}")
    else:
        print(render())
